ZDIR = PKG.parent / "BMC_MIDM_FEASIBILITY_FINAL_AUDIT_ZIPS"; ZDIR.mkdir(exist_ok=True)
report = []
for zname, parts in ZIPS.items():
    zp = ZDIR / zname
    with zipfile.ZipFile(zp, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for part in parts:
            p = PKG / part
            if p.is_file():
                z.write(p, p.relative_to(PKG).as_posix())
            else:
                for f in sorted(p.rglob("*")):
                    if f.is_file():
                        z.write(f, f.relative_to(PKG).as_posix())
    with zipfile.ZipFile(zp) as z:
        bad = z.testzip(); n = len(z.namelist())
    size = zp.stat().st_size
    status = "OK" if bad is None else f"CORRUPT: {bad}"
    assert size <= ZIP_HARD, f"{zname} exceeds 12 MB: {size}"
    if size > ZIP_SOFT:
        print(f"WARNING: {zname} exceeds the 8 MB target ({size/1e6:.2f} MB)")
    report.append((zname, size, n, status))
total = sum(s for _, s, _, _ in report)
with open(PKG / "ZIP_REPORT.txt", "w", encoding="utf-8") as f:
    for zname, size, n, status in report:
        f.write(f"{zname}\t{size/1e6:.2f} MB\t{n} files\ttestzip: {status}\n")
    f.write(f"TOTAL\t{total/1e6:.2f} MB\n")
print(open(PKG / "ZIP_REPORT.txt").read())

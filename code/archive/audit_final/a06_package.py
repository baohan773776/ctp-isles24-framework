"""Assemble the lightweight audit package, manifests, SHA256SUMS and ZIP archives; test every ZIP.

Portable: paths derive from this file's location (analysis_v3/audit_final) or from the environment variables
BRANCH3_WS (workspace root), BRANCH3_OUT (folder with tables/, oof/, data/, figures/), ISLES24_DIR (pre-processed release).
Usage: python a06_package.py [package_dir]
Run after s11/s12 (manuscript, additional files), a01 (inventory), a02 (ledger), a03 (claim matrix), a05 (cover letter).
Original project files are only read. The provenance documents are copied from audit_final/provenance/.
"""
